async function main() {
  console.log(`Seeding ${specimensToSeed.length} remaining specimens into DB...`);
  for (const item of specimensToSeed) {
    const existing = await prisma.product.findUnique({ where: { id: item.id } });
    if (existing) {
      console.log(`[EXISTS] Product ${item.id} already in database.`);
    } else {
      await prisma.product.create({
        data: {
          id: item.id,
          sku: item.sku,
          name: item.name,
          brand: item.brand,
          category: item.category,
          price: item.price,
          mrp: item.mrp,
          isActive: true,
          catalog: item.catalog,
        },
      });
      console.log(`[CREATED] Seeded Product ${item.id} (${item.name}) into database.`);
    }
  }

  const finalCount = await prisma.product.count();
  console.log(`Done! Total products in database: ${finalCount}`);
}

main()
  .catch((e) => {
    console.error('Seeding error:', e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
